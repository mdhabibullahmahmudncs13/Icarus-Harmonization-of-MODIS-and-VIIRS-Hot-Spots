"""Pre-registered validation experiments E1-E9 (docs/TESTING.md §9).

Every experiment is deterministic, network-free and takes canonical detections
(the same table the API serves). Each returns an :class:`Experiment` carrying a
verdict, scalar metrics, a table, a figure spec and limitation notes, so the
report can be regenerated byte-for-byte from the same inputs and parameter set.

Design, metric and decision rule are fixed before the run: see ``docs/VALIDATION.md``
for the report this module writes. Negative results are reported, not hidden.
"""

from __future__ import annotations

import math
import random
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import date, timedelta
from typing import Any

import numpy as np
import pandas as pd

from src.compute import calibrate, export, harmonize, schema, season
from src.compute import validate as validation

#: Median absolute log-offset a calibrated series must stay under (E2).
#: Pre-registered for this report: a factor of ~1.28 in either direction.
CALIBRATION_OFFSET_CEILING = 0.25

#: Confidence thresholds swept by E3 (docs/PARAMETERS.md ``c_min``).
CONFIDENCE_SWEEP: tuple[float, ...] = (20.0, 30.0, 40.0, 50.0)

#: Static-mask date thresholds swept by E4 (docs/PARAMETERS.md ``min_days``).
MIN_DAYS_SWEEP: tuple[int, ...] = (8, 16, 32)

#: The VIIRS satellites the pipeline ingests, as ``satellite_product`` values.
VIIRS_LABELS: tuple[str, ...] = ("Suomi-NPP", "NOAA-20", "NOAA-21")

_VERDICT_SUPPORTED = "supported"
_VERDICT_PARTIAL = "partial"
_VERDICT_NOT_SUPPORTED = "not supported"
_VERDICT_LIMITATION = "limitation"


@dataclass
class Experiment:
    """One E-numbered experiment and everything the report shows for it."""

    id: str
    title: str
    question: str
    decision_rule: str
    verdict: str
    metrics: dict[str, Any] = field(default_factory=dict)
    table: list[dict[str, Any]] = field(default_factory=list)
    figure: dict[str, Any] | None = None
    notes: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "title": self.title,
            "question": self.question,
            "decision_rule": self.decision_rule,
            "verdict": self.verdict,
            "metrics": self.metrics,
            "table": self.table,
            "figure": self.figure,
            "notes": list(self.notes),
        }


# --------------------------------------------------------------------------
# Small shared helpers
# --------------------------------------------------------------------------


def _number(value: Any, dp: int = 4) -> float | None:
    """A finite rounded float, or ``None`` — never ``NaN`` (invalid JSON)."""
    if value is None:
        return None
    number = float(value)
    return round(number, dp) if math.isfinite(number) else None


def _step_ratio(pre: pd.Series, post: pd.Series) -> float:
    """``mean(post) / mean(pre)`` for two daily series windows."""
    if pre.empty or post.empty:
        return float("nan")
    base = float(pre.mean())
    return float(post.mean() / base) if base else float("nan")


def _around(series: pd.Series, transition: date, years: int = 2) -> tuple[pd.Series, pd.Series]:
    """Split a daily series into ``years`` before and after ``transition``."""
    stamp = pd.Timestamp(transition)
    pre = series[(series.index >= stamp - pd.DateOffset(years=years)) & (series.index < stamp)]
    post = series[(series.index >= stamp) & (series.index < stamp + pd.DateOffset(years=years))]
    return pre, post


def _series_rows(series: pd.Series, key: str = "harm_total") -> list[dict[str, Any]]:
    """Daily series as the ``{"date":..., "harm_total":...}`` rows season reads."""
    return [{"date": index.strftime("%Y-%m-%d"), key: float(value)} for index, value in series.items()]


def _first_viirs_date(detections: pd.DataFrame) -> date:
    dates = detections.loc[detections["sensor_family"] == schema.VIIRS, "acq_date"]
    if dates.empty:
        raise ValueError("no VIIRS detections; the join date is undefined")
    return dates.min().date()


def _harmonized(detections: pd.DataFrame, **kwargs: Any) -> pd.DataFrame:
    return harmonize.harmonize(detections, **kwargs)


# --------------------------------------------------------------------------
# E1 — step-change detection (artificial cell-day step)
# --------------------------------------------------------------------------


def synthetic_step(
    *,
    days: int = 730,
    join: int = 365,
    base_cells: int = 40,
    viirs_duplicates: int = 2,
    extra_viirs_cells: int = 6,
    seed: int = 20260101,
    start: date = date(2011, 1, 1),
) -> pd.DataFrame:
    """A two-sensor table with an *artificial* step at the VIIRS join.

    Before ``join`` only MODIS reports, one detection per active cell. After
    the join VIIRS reports ``viirs_duplicates`` extra detections in the *same*
    cells (the sensor's density, not new fires) plus ``extra_viirs_cells``
    genuinely new cells. Raw counts jump by the density; cell-day counts do
    not. The generator is seeded, so the same call yields the same table.
    """
    rng = random.Random(seed)
    rows: list[dict[str, object]] = []

    def place(index: int) -> tuple[float, float]:
        return (20.0 + (index // 20) * 0.05, 80.0 + (index % 20) * 0.05)

    for offset in range(days):
        day = start + timedelta(days=offset)
        after = offset >= join
        for cell in range(base_cells):
            latitude, longitude = place(cell)
            rows.append(
                {
                    "latitude": latitude,
                    "longitude": longitude,
                    "acq_date": day.isoformat(),
                    "confidence": 80,
                    "instrument": "MODIS",
                }
            )
            if after:
                for _ in range(viirs_duplicates):
                    rows.append(
                        {
                            "latitude": latitude,
                            "longitude": longitude,
                            "acq_date": day.isoformat(),
                            "confidence": rng.choice(["n", "n", "h"]),
                            "instrument": "VIIRS",
                        }
                    )
        if after:
            for cell in range(extra_viirs_cells):
                latitude, longitude = place(base_cells + cell)
                rows.append(
                    {
                        "latitude": latitude,
                        "longitude": longitude,
                        "acq_date": day.isoformat(),
                        "confidence": "n",
                        "instrument": "VIIRS",
                    }
                )

    frame = pd.DataFrame(rows)
    return frame.sort_values(["acq_date", "instrument"], kind="stable").reset_index(drop=True)


def experiment_e1(detections: pd.DataFrame, transition: date) -> Experiment:
    """E1 — an artificial cell-day step at the VIIRS join shrinks under harmonization."""
    synthetic_raw = synthetic_step()
    synthetic = _harmonized(synthetic_raw)
    join = pd.Timestamp(date(2011, 1, 1) + timedelta(days=365))

    raw_series = harmonize.raw_series(synthetic)
    harm_series = harmonize.harmonized_series(synthetic)
    raw_pre, raw_post = raw_series[raw_series.index < join], raw_series[raw_series.index >= join]
    harm_pre, harm_post = harm_series[harm_series.index < join], harm_series[harm_series.index >= join]

    raw_step = _step_ratio(raw_pre, raw_post)
    harm_step = _step_ratio(harm_pre, harm_post)

    # The real join, for contrast — same computation, observed data.
    real = _harmonized(detections)
    real_raw = harmonize.raw_series(real)
    real_harm = harmonize.harmonized_series(real)
    obs_raw = _step_ratio(*_around(real_raw, transition))
    obs_harm = _step_ratio(*_around(real_harm, transition))

    reduction = (raw_step - harm_step) / (raw_step - 1.0) if raw_step > 1.0 else float("nan")
    verdict = _VERDICT_SUPPORTED if harm_step < raw_step else _VERDICT_NOT_SUPPORTED

    return Experiment(
        id="E1",
        title="Step-change detection",
        question="Does the artificial cell-day step at the VIIRS join shrink after harmonization?",
        decision_rule="The harmonized step is smaller than the raw step at the same join.",
        verdict=verdict,
        metrics={
            "synthetic_raw_step": _number(raw_step),
            "synthetic_harmonized_step": _number(harm_step),
            "step_removed_fraction": _number(reduction),
            "observed_raw_step": _number(obs_raw),
            "observed_harmonized_step": _number(obs_harm),
        },
        table=[
            {"join": "artificial (seeded)", "raw_step": _number(raw_step), "harmonized_step": _number(harm_step)},
            {"join": f"observed ({transition.isoformat()})", "raw_step": _number(obs_raw), "harmonized_step": _number(obs_harm)},
        ],
        figure={
            "kind": "bars",
            "categories": ["Raw", "Harmonized"],
            "y_label": "step ratio (post / pre)",
            "series": [
                {"label": "artificial", "values": [_number(raw_step), _number(harm_step)]},
                {"label": "observed", "values": [_number(obs_raw), _number(obs_harm)]},
            ],
            "reference": 1.0,
        },
        notes=[
            "The artificial step is generated (docs/TESTING.md §9 E1); it is a mechanism check, not evidence about real fires.",
            "The observed step is the real MODIS/VIIRS join from the cache and is reported honestly, not tuned away.",
            (
                "Observed windows are two years either side of the join "
                "(2010-01-20..2012-01-20 vs 2012-01-20..2014-01-20), so these ratios differ from the "
                "Phase 4 finding in docs/IMPLEMENTATION_PLAN.md §6.1, which uses the 2010-11 and "
                "2013-14 windows."
            ),
        ],
    )


# --------------------------------------------------------------------------
# E2 — calibration residual offset, leave-one-year-out
# --------------------------------------------------------------------------


def experiment_e2(detections: pd.DataFrame) -> Experiment:
    """E2 — calibrated median |offset| below the ceiling over leave-one-year-out."""
    frame = _harmonized(detections)
    start, end = validation.overlap_window(frame)
    overlap = frame[
        (frame["acq_date"] >= pd.Timestamp(start)) & (frame["acq_date"] <= pd.Timestamp(end))
    ].copy()
    years = sorted({int(year) for year in overlap["acq_date"].dt.year})
    if len(years) < 2:
        return Experiment(
            id="E2",
            title="Calibration residual offset",
            question="Is the calibrated median |offset| below the ceiling over leave-one-year-out?",
            decision_rule=f"Median |log offset| <= {CALIBRATION_OFFSET_CEILING}.",
            verdict=_VERDICT_LIMITATION,
            notes=[
                f"Only {len(years)} overlap year(s) available; leave-one-year-out needs at least two.",
                "Not evaluable on this input — reported as a limitation rather than fabricated.",
            ],
        )

    rows: list[dict[str, Any]] = []
    calibrated_offsets: list[float] = []
    raw_offsets: list[float] = []
    for year in years:
        train = overlap[overlap["acq_date"].dt.year != year]
        test = overlap[overlap["acq_date"].dt.year == year]
        factors = calibrate.factor_by_month(train)
        modis = harmonize.harmonized_series(test[test["sensor_family"] == schema.MODIS])
        viirs = harmonize.harmonized_series(test[test["sensor_family"] == schema.VIIRS])
        for stamp in modis.index.union(viirs.index):
            m = float(modis.get(stamp, 0.0))
            v = float(viirs.get(stamp, 0.0))
            factor = factors.get(int(stamp.month), calibrate.NEUTRAL_FACTOR)
            raw_offsets.append(abs(math.log((v + 1.0) / (m + 1.0))))
            calibrated_offsets.append(abs(math.log((v * factor + 1.0) / (m + 1.0))))
        rows.append(
            {
                "year": year,
                "days": len(modis.index.union(viirs.index)),
                "median_abs_offset_raw": _number(np.median(raw_offsets[-len(modis.index.union(viirs.index)):])),
                "median_abs_offset_calibrated": _number(np.median(calibrated_offsets[-len(modis.index.union(viirs.index)):])),
            }
        )

    overall_raw = float(np.median(raw_offsets)) if raw_offsets else float("nan")
    overall_calibrated = float(np.median(calibrated_offsets)) if calibrated_offsets else float("nan")
    supported = math.isfinite(overall_calibrated) and overall_calibrated <= CALIBRATION_OFFSET_CEILING
    improved = overall_calibrated < overall_raw

    return Experiment(
        id="E2",
        title="Calibration residual offset",
        question="Does calibration pull the VIIRS/MODIS cell-day ratio toward 1 on held-out years?",
        decision_rule=f"Leave-one-year-out median |log offset| <= {CALIBRATION_OFFSET_CEILING} (≈ ±28%).",
        verdict=_VERDICT_SUPPORTED if supported else (_VERDICT_PARTIAL if improved else _VERDICT_NOT_SUPPORTED),
        metrics={
            "overlap_start": start.isoformat(),
            "overlap_end": end.isoformat(),
            "overlap_years": len(years),
            "median_abs_offset_raw": _number(overall_raw),
            "median_abs_offset_calibrated": _number(overall_calibrated),
            "ceiling": CALIBRATION_OFFSET_CEILING,
        },
        table=rows,
        figure={
            "kind": "bars",
            "categories": ["Raw", "Calibrated"],
            "y_label": "median |log offset|",
            "series": [
                {
                    "label": "leave-one-year-out",
                    "values": [_number(overall_raw), _number(overall_calibrated)],
                }
            ],
            "reference": CALIBRATION_OFFSET_CEILING,
        },
        notes=[
            "Offset is |log((VIIRS cell-days + 1) / (MODIS cell-days + 1))| per day; the median is over held-out days.",
            f"The ceiling {CALIBRATION_OFFSET_CEILING} is pre-registered for this report; it is not a published value.",
        ],
    )


# --------------------------------------------------------------------------
# E3 — sensitivity to the quality threshold
# --------------------------------------------------------------------------


def experiment_e3(detections: pd.DataFrame, transition: date) -> Experiment:
    """E3 — how the series and the count respond to ``c_min``."""
    rows: list[dict[str, Any]] = []
    retained: list[float] = []
    steps: list[float] = []
    for threshold in CONFIDENCE_SWEEP:
        frame = _harmonized(detections, min_confidence=threshold)
        harm = harmonize.harmonized_series(frame)
        raw = harmonize.raw_series(frame)
        step = _step_ratio(*_around(harm, transition))
        kept = len(frame) / max(len(detections), 1)
        retained.append(kept)
        steps.append(step)
        rows.append(
            {
                "c_min": threshold,
                "detections_kept": len(frame),
                "kept_fraction": _number(kept),
                "mean_harmonized_per_day": _number(float(harm.mean()) if len(harm) else 0.0),
                "mean_raw_per_day": _number(float(raw.mean()) if len(raw) else 0.0),
                "harmonized_step": _number(step),
            }
        )

    span = (max(retained) - min(retained)) if retained else float("nan")
    return Experiment(
        id="E3",
        title="Sensitivity to the quality threshold",
        question="How much do the series and the step move when c_min varies?",
        decision_rule="Report the change; no pass/fail. A large swing means the result is threshold-fragile.",
        verdict=_VERDICT_SUPPORTED if math.isfinite(span) and span <= 0.2 else _VERDICT_PARTIAL,
        metrics={
            "c_min_values": list(CONFIDENCE_SWEEP),
            "kept_fraction_span": _number(span),
            "harmonized_step_span": _number(max(steps) - min(steps)) if steps else None,
        },
        table=rows,
        figure={
            "kind": "lines",
            "x": [str(value) for value in CONFIDENCE_SWEEP],
            "x_label": "c_min",
            "y_label": "mean harmonized cell-days / day",
            "series": [
                {
                    "label": "mean per day",
                    "values": [row["mean_harmonized_per_day"] for row in rows],
                }
            ],
        },
        notes=[
            "The default c_min is 30 (docs/PARAMETERS.md); the higher thresholds trade sensitivity for specificity.",
            "Detections kept is the share of the raw table that survives the cut after the VIIRS confidence mapping.",
        ],
    )


# --------------------------------------------------------------------------
# E4 — static-mask sensitivity
# --------------------------------------------------------------------------


def experiment_e4(detections: pd.DataFrame) -> Experiment:
    """E4 — what a static activity mask at each ``min_days`` would remove."""
    frame = _harmonized(detections)
    per_cell = frame.groupby("cell_id")["acq_date"].nunique()
    cell_days = frame.groupby("cell_id").size()
    total_days = int(cell_days.sum())
    rows: list[dict[str, Any]] = []
    for threshold in MIN_DAYS_SWEEP:
        removed = per_cell[per_cell < threshold]
        removed_cells = len(removed)
        removed_mass = int(cell_days.loc[removed.index].sum()) if removed_cells else 0
        rows.append(
            {
                "min_days": threshold,
                "cells_removed": removed_cells,
                "cells_removed_fraction": _number(removed_cells / max(len(per_cell), 1)),
                "cell_days_removed_fraction": _number(removed_mass / max(total_days, 1)),
            }
        )

    worst = max((row["cell_days_removed_fraction"] or 0.0) for row in rows)
    return Experiment(
        id="E4",
        title="Static-mask sensitivity",
        question="What fraction of cells and cell-days would a static activity mask remove at each min_days?",
        decision_rule="Report the removal fraction; no pass/fail. A large fraction means the mask would bite.",
        verdict=_VERDICT_SUPPORTED if math.isfinite(worst) and worst <= 0.5 else _VERDICT_PARTIAL,
        metrics={
            "cells_total": len(per_cell),
            "min_days_values": list(MIN_DAYS_SWEEP),
            "max_cell_days_removed_fraction": _number(worst),
        },
        table=rows,
        figure={
            "kind": "bars",
            "categories": [str(value) for value in MIN_DAYS_SWEEP],
            "x_label": "min_days",
            "y_label": "fraction of cell-days removed",
            "series": [
                {
                    "label": "cell-days removed",
                    "values": [row["cell_days_removed_fraction"] for row in rows],
                }
            ],
        },
        notes=[
            "The pipeline as built applies no static activity mask; this reports what one would remove.",
            "Removal is measured on the working grid (cell-days), not the documented ~550 m fine grid.",
        ],
    )


# --------------------------------------------------------------------------
# E5 — non-linear calibration diagnostics
# --------------------------------------------------------------------------


def experiment_e5(detections: pd.DataFrame) -> Experiment:
    """E5 — multiplicative vs log-log vs quantile mapping at tile level."""
    frame = _harmonized(detections)
    counts = calibrate.active_cell_days(frame)
    counts = counts[(counts["m_sum"] > 0) & (counts["v_sum"] > 0)].copy()
    if counts.empty:
        return Experiment(
            id="E5",
            title="Non-linear calibration diagnostics",
            question="Do log-log or quantile mapping beat multiplicative at tile level?",
            decision_rule="Report median |log residual| per method; lower is better.",
            verdict=_VERDICT_LIMITATION,
            notes=["No tile/month with both MODIS and VIIRS activity; not evaluable on this input."],
        )

    m = counts["m_sum"].to_numpy(dtype="float64")
    v = counts["v_sum"].to_numpy(dtype="float64")
    regional = calibrate.regional_factor(counts)

    def residual(predicted: np.ndarray) -> float:
        return float(np.median(np.abs(np.log((predicted + 1.0) / (m + 1.0)))))

    multiplicative = np.array(
        [regional.get(int(month), calibrate.NEUTRAL_FACTOR) for month in counts["month"]]
    ) * v

    # log-log: least squares fit of log(m+1) on log(v+1), closed form (no scipy).
    lx, ly = np.log(v + 1.0), np.log(m + 1.0)
    slope = float(np.cov(lx, ly, bias=True)[0, 1] / np.var(lx)) if float(np.var(lx)) else 0.0
    intercept = float(ly.mean() - slope * lx.mean())
    loglog = np.exp(intercept + slope * lx) - 1.0

    # quantile mapping: map each v's empirical rank to the same m quantile.
    order = np.argsort(v)
    m_sorted = np.sort(m)
    quantile = np.empty_like(v)
    quantile[order] = m_sorted

    methods = [
        ("multiplicative", multiplicative),
        ("log-log", loglog),
        ("quantile mapping", quantile),
    ]
    rows = [
        {"method": name, "median_abs_log_residual": _number(residual(predicted))}
        for name, predicted in methods
    ]
    best = min(rows, key=lambda row: row["median_abs_log_residual"] or 1e9)

    return Experiment(
        id="E5",
        title="Non-linear calibration diagnostics",
        question="Do log-log or quantile mapping beat multiplicative at tile level?",
        decision_rule="Report median |log residual| per method; lower is better.",
        verdict=_VERDICT_SUPPORTED if best["method"] else _VERDICT_LIMITATION,
        metrics={
            "tiles": len(counts),
            "loglog_slope": _number(slope),
            "loglog_intercept": _number(intercept),
            "best_method": best["method"],
        },
        table=rows,
        figure={
            "kind": "bars",
            "categories": [row["method"] for row in rows],
            "y_label": "median |log residual|",
            "series": [
                {"label": "residual", "values": [row["median_abs_log_residual"] for row in rows]}
            ],
        },
        notes=[
            "Residual is |log((predicted + 1) / (MODIS + 1))| at the 1° tile / month level.",
            "Quantile mapping is in-sample here (it uses the same tiles it scores) and is optimistic by construction.",
        ],
    )


# --------------------------------------------------------------------------
# E6 — temporal resolution
# --------------------------------------------------------------------------


def _resample(series: pd.Series, days: int) -> pd.Series:
    """Sum a daily series into ``days``-wide bins anchored on the first date.

    The bin keeps the datetime index of its first day, so the step windows in
    :func:`_around` still apply to the resampled series.
    """
    if days <= 1 or series.empty:
        return series
    origin = series.index.min()
    offsets = ((series.index - origin).days // days) * days
    grouped = series.groupby(offsets).sum()
    grouped.index = pd.DatetimeIndex([origin + pd.Timedelta(days=int(offset)) for offset in grouped.index])
    grouped.index.name = "date"
    return grouped


def experiment_e6(detections: pd.DataFrame, transition: date) -> Experiment:
    """E6 — daily vs weekly vs 8-day resolution on the step and the critical period."""
    frame = _harmonized(detections)
    daily = harmonize.harmonized_series(frame)
    rows: list[dict[str, Any]] = []
    for label, days in (("daily", 1), ("weekly", 7), ("8-day", 8)):
        series = _resample(daily, days) if days > 1 else daily
        pre, post = _around(series, transition, years=2)
        period = season.critical_period(_series_rows(series), bin_days=season.BIN_DAYS)
        rows.append(
            {
                "resolution": label,
                "bins": len(series),
                "mean_per_bin": _number(float(series.mean()) if len(series) else 0.0),
                "step_ratio": _number(_step_ratio(pre, post)),
                "onset_bin": period["onset_bin"],
                "peak_bin": period["peak_bin"],
                "end_bin": period["end_bin"],
            }
        )

    peaks = {row["peak_bin"] for row in rows}
    return Experiment(
        id="E6",
        title="Temporal resolution",
        question="Do weekly and 8-day views change the step or the critical period?",
        decision_rule="The seasonal peak bin is stable across resolutions; report step and timing.",
        verdict=_VERDICT_SUPPORTED if len(peaks) == 1 else _VERDICT_PARTIAL,
        metrics={"peak_bin_stable": len(peaks) == 1, "resolutions": [row["resolution"] for row in rows]},
        table=rows,
        figure={
            "kind": "bars",
            "categories": [row["resolution"] for row in rows],
            "x_label": "resolution",
            "y_label": "step ratio (post / pre)",
            "series": [{"label": "step", "values": [row["step_ratio"] for row in rows]}],
            "reference": 1.0,
        },
        notes=[
            "The critical period is computed on the whole series, not just the overlap, at 8-day doy bins.",
            "Weekly and 8-day bins aggregate more activity and are less sensitive to single-day outliers.",
        ],
    )


# --------------------------------------------------------------------------
# E7 — VIIRS satellite inclusion
# --------------------------------------------------------------------------


def experiment_e7(detections: pd.DataFrame, transition: date) -> Experiment:
    """E7 — S-NPP only vs adding NOAA-20 and NOAA-21.

    Needs a ``satellite_product`` label per row. When the input only carries a
    sensor family (the offline fixture), the sweep collapses to a single
    "all VIIRS" group and that is reported as a limitation.
    """
    frame = _harmonized(detections)
    notes = [
        "Adding satellites changes the raw density and the overlap only from the later satellites' epochs.",
        "NOAA-21 is ingested from the NRT source (the FIRMS Area API serves no SP source for it).",
    ]
    if "satellite_product" in frame.columns:
        labels = frame["satellite_product"].astype(str)
        sweep = [label for label in VIIRS_LABELS if bool((labels == label).any())]
    else:
        labels = pd.Series([""] * len(frame), index=frame.index)
        sweep = []
        notes.append(
            "Input carries no per-satellite label, so the S-NPP / NOAA-20 / NOAA-21 sweep "
            "collapses to a single 'all VIIRS' group."
        )

    rows: list[dict[str, Any]] = []
    included: list[str] = []
    for label in sweep if sweep else [None]:
        if label is not None:
            included.append(label)
        mask = frame["sensor_family"] == schema.MODIS
        if included:
            mask = mask | (
                (frame["sensor_family"] == schema.VIIRS) & labels.isin(included)
            )
        else:
            mask = mask | (frame["sensor_family"] == schema.VIIRS)
        subset = frame[mask]
        harm = harmonize.harmonized_series(subset)
        modis = harmonize.harmonized_series(subset[subset["sensor_family"] == schema.MODIS])
        viirs = harmonize.harmonized_series(subset[subset["sensor_family"] == schema.VIIRS])
        correlation = validation.correlation_stats(modis, viirs)
        rows.append(
            {
                "included": " + ".join(included) if included else "all VIIRS",
                "viirs_cell_days": int(viirs.sum()),
                "step_ratio": _number(_step_ratio(*_around(harm, transition))),
                "modis_viirs_pearson": _number(correlation.pearson),
                "modis_viirs_ratio": _number(correlation.ratio),
            }
        )

    return Experiment(
        id="E7",
        title="VIIRS satellite inclusion",
        question="What changes when NOAA-20 and NOAA-21 join S-NPP?",
        decision_rule="Report the step, overlap correlation and ratio as satellites accumulate; no pass/fail.",
        verdict=_VERDICT_SUPPORTED if sweep else _VERDICT_PARTIAL,
        metrics={
            "satellites_swept": list(sweep),
            "groups": len(rows),
            "final_viirs_cell_days": rows[-1]["viirs_cell_days"],
        },
        table=rows,
        figure={
            "kind": "lines",
            "x": [row["included"] for row in rows],
            "x_label": "VIIRS included",
            "y_label": "step ratio (post / pre)",
            "series": [{"label": "step", "values": [row["step_ratio"] for row in rows]}],
            "reference": 1.0,
        },
        notes=notes,
    )


