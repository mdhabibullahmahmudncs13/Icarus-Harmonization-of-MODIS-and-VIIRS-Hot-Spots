# E9 — offline performance
# --------------------------------------------------------------------------


def experiment_e9(
    cache_dir: Any,
    *,
    api_latency_s: float | None = None,
    cold_start_s: float | None = None,
) -> Experiment:
    """E9 — cache size, API latency, cold start; Lighthouse is a limitation."""
    from pathlib import Path

    root = Path(cache_dir) if cache_dir is not None else None
    cache_bytes = 0
    files = 0
    if root is not None and root.exists():
        for path in root.rglob("*"):
            if path.is_file():
                cache_bytes += path.stat().st_size
                files += 1
    return Experiment(
        id="E9",
        title="Offline performance",
        question="How big is the cache, how fast is the API, how fast is an offline cold start?",
        decision_rule="Measure and report each; Lighthouse and a real-device start are reported as limitations.",
        verdict=_VERDICT_PARTIAL,
        metrics={
            "cache_bytes": int(cache_bytes),
            "cache_mib": _number(cache_bytes / (1024 * 1024), 2),
            "cache_files": files,
            "api_latency_s": _number(api_latency_s, 3),
            "cold_start_s": _number(cold_start_s, 3),
        },
        table=[
            {"metric": "cache size", "value": f"{cache_bytes / (1024 * 1024):.1f} MiB ({files} files)"},
            {"metric": "API latency", "value": "not measured" if api_latency_s is None else f"{api_latency_s:.3f} s"},
            {"metric": "offline cold start", "value": "not measured" if cold_start_s is None else f"{cold_start_s:.2f} s"},
            {"metric": "Lighthouse PWA score", "value": "not run (no headless Chrome/Lighthouse in this environment)"},
        ],
        notes=[
            "The offline cold start is automated in web/e2e/offline-cold-start.spec.ts; the real-device run and the fallback video are not recorded.",
            "Lighthouse is not installed here, so its PWA score is reported as a limitation, not a number.",
        ],
    )


